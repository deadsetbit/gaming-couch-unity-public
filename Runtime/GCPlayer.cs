        private enum GCPlayerStateTimestampTarget
        {
            Permanent,
            Revokable,
            Revoke,
        }

        private void ApplyEliminationTransition(
            GCPlayerTransitionResult<GCPlayerEliminationState> transition,
            GCPlayerStateTimestampTarget timestampTarget,
            string logAction
        )
        {
            var oldState = transition.PreviousValue;
            var changedAtGameTime = transition.ChangedAtGameTime;
            eliminationState = transition.Value;

            switch (timestampTarget)
            {
                case GCPlayerStateTimestampTarget.Permanent:
                    lastSetEliminatedPermanentGameTime = changedAtGameTime;
                    lastSetEliminatedGameTime = changedAtGameTime;
                    break;
                case GCPlayerStateTimestampTarget.Revokable:
                    lastSetEliminatedRevokableGameTime = changedAtGameTime;
                    lastSetEliminatedGameTime = changedAtGameTime;
                    break;
                case GCPlayerStateTimestampTarget.Revoke:
                    lastSetRevokeEliminatedGameTime = changedAtGameTime;
                    lastSetRevokeGameTime = changedAtGameTime;
                    break;
            }

            GCLog.LogInfo($"Player index {index} {logAction} - reason: " + transition.ReasonText);
            AcceptedTransition?.Invoke(GCPlayerAcceptedTransition.FromElimination(transition));
            OnEliminationStateChanged?.Invoke(new GCPlayerEliminationStateChangedEventArgs(
                index,
                oldState,
                eliminationState,
                transition.ReasonText,
                changedAtGameTime
            ));
        }

        private void ApplyFinishTransition(
            GCPlayerTransitionResult<GCPlayerFinishState> transition,
            GCPlayerStateTimestampTarget timestampTarget,
            string logAction
        )
        {
            var oldState = transition.PreviousValue;
            var changedAtGameTime = transition.ChangedAtGameTime;
            finishState = transition.Value;

            switch (timestampTarget)
            {
                case GCPlayerStateTimestampTarget.Permanent:
                    lastSetFinishedPermanentGameTime = changedAtGameTime;
                    lastSetFinishedGameTime = changedAtGameTime;
                    break;
                case GCPlayerStateTimestampTarget.Revokable:
                    lastSetFinishedRevokableGameTime = changedAtGameTime;
                    lastSetFinishedGameTime = changedAtGameTime;
                    break;
                case GCPlayerStateTimestampTarget.Revoke:
                    lastSetRevokeFinishedGameTime = changedAtGameTime;
                    lastSetRevokeGameTime = changedAtGameTime;
                    break;
            }

            GCLog.LogInfo($"Player index {index} {logAction} - reason: " + transition.ReasonText);
            AcceptedTransition?.Invoke(GCPlayerAcceptedTransition.FromFinish(transition));
            OnFinishStateChanged?.Invoke(new GCPlayerFinishStateChangedEventArgs(
                index,
                oldState,
                finishState,
                transition.ReasonText,
                changedAtGameTime
            ));
        }

        private void ApplyScoreTransition(GCPlayerTransitionResult<int> transition)
        {
            var oldScore = transition.PreviousValue;
            score = transition.Value;

            GCLog.LogInfo($"Player index {index} score set to {score} - reason: " + transition.ReasonText);
            AcceptedTransition?.Invoke(GCPlayerAcceptedTransition.FromInt(transition));
            OnScoreChanged?.Invoke(oldScore, score, transition.ReasonText);
        }

        private void ApplyLivesTransition(GCPlayerTransitionResult<int> transition)
        {
            var oldLives = transition.PreviousValue;
            lives = transition.Value;

            GCLog.LogInfo($"Player index {index} lives set to {lives} - reason: " + transition.ReasonText);
            AcceptedTransition?.Invoke(GCPlayerAcceptedTransition.FromInt(transition));
            OnLivesChanged?.Invoke(oldLives, lives, transition.ReasonText);
        }

        private void ApplyStatusTransition(GCPlayerTransitionResult<GCPlayerStatusValue> transition)
        {
            var oldValue = transition.PreviousValue;
            var value = transition.Value;

            GCLog.LogInfo($"Player index {index} status set to {value.Status} with text {value.StatusText} - reason: " + transition.ReasonText);

            status = value.Status;
            statusText = value.StatusText;

            AcceptedTransition?.Invoke(GCPlayerAcceptedTransition.FromStatus(transition));
            OnStatusTransitionChanged?.Invoke(
                oldValue.Status,
                oldValue.StatusText,
                status,
                statusText,
                transition.ReasonText
            );
            OnStatusChanged?.Invoke(status, statusText, transition.ReasonText);
        }

        private void ApplyMeterTransition(GCPlayerTransitionResult<int> transition)
        {
            var oldMeter = transition.PreviousValue;
            meter = transition.Value;

            AcceptedTransition?.Invoke(GCPlayerAcceptedTransition.FromInt(transition));
            OnMeterChanged?.Invoke(oldMeter, meter, transition.ReasonText);
        }

        private void EmitEliminationTransitionDiagnostic(
            string mutatorName,
            GCPlayerTransitionResult<GCPlayerEliminationState> transition
        )
        {
            EmitStateTransitionDiagnostic(
                mutatorName,
                transition,
                permanentState: GCPlayerEliminationState.Permanent,
                duplicateCode: GCDiagnosticCodes.DuplicateElimination,
                duplicatePermanentMessage: "Player is already permanently eliminated.",
                duplicateRevokableMessage: "Player is already revokably eliminated.",
                invalidTransitionMessage: "Permanent elimination cannot transition back to revokable elimination.",
                invalidRevokeMessage: "Only revokable elimination can be revoked."
            );
        }

        private void EmitFinishTransitionDiagnostic(
            string mutatorName,
            GCPlayerTransitionResult<GCPlayerFinishState> transition
        )
        {
            EmitStateTransitionDiagnostic(
                mutatorName,
                transition,
                permanentState: GCPlayerFinishState.Permanent,
                duplicateCode: GCDiagnosticCodes.DuplicateFinish,
                duplicatePermanentMessage: "Player is already permanently finished.",
                duplicateRevokableMessage: "Player is already revokably finished.",
                invalidTransitionMessage: "Permanent finish cannot transition back to revokable finish.",
                invalidRevokeMessage: "Only revokable finish can be revoked."
            );
        }

        // Elimination and finish stay independent enums per ADR 0003, but they reject for the same
        // three reasons, so the diagnostic path is shared and each family supplies only its wording.
        private void EmitStateTransitionDiagnostic<TState>(
            string mutatorName,
            GCPlayerTransitionResult<TState> transition,
            TState permanentState,
            string duplicateCode,
            string duplicatePermanentMessage,
            string duplicateRevokableMessage,
            string invalidTransitionMessage,
            string invalidRevokeMessage
        ) where TState : struct, Enum
        {
            var oldState = transition.PreviousValue.ToString();
            var requestedState = transition.Value.ToString();

            switch (transition.RejectionReason)
            {
                case GCPlayerTransitionRejectionReason.DuplicateValue:
                    EmitStateDiagnostic(
                        duplicateCode,
                        EqualityComparer<TState>.Default.Equals(transition.Value, permanentState)
                            ? duplicatePermanentMessage
                            : duplicateRevokableMessage,
                        mutatorName,
                        oldState,
                        requestedState
                    );
                    return;
                case GCPlayerTransitionRejectionReason.InvalidTransition:
                    EmitStateDiagnostic(
                        GCDiagnosticCodes.InvalidTransition,
                        invalidTransitionMessage,
                        mutatorName,
                        oldState,
                        requestedState
                    );
                    return;
                case GCPlayerTransitionRejectionReason.InvalidRevoke:
                    EmitStateDiagnostic(
                        GCDiagnosticCodes.InvalidRevoke,
                        invalidRevokeMessage,
                        mutatorName,
                        oldState,
                        requestedState
                    );
                    return;
            }
        }

        private bool TryAllowMutation(string mutatorName)
        {
            if (GamingCouch.Instance == null || GamingCouch.Instance.Status != GCStatus.GameOver)
            {
                return true;
            }

            EmitStateDiagnostic(
                GCDiagnosticCodes.PostGameOverMutation,
                "Player mutation after game over was ignored.",
                mutatorName,
                null,
                null
            );
            return false;
        }

        private void EmitStateDiagnostic(
            string code,
            string message,
            string mutatorName,
            string oldState,
            string requestedState
        )
        {
            var context = new GCDiagnosticContext()
                .AddDetail("mutator", mutatorName);

            if (index >= 0)
            {
                context.WithPlayerIndex(index);
            }

            if (oldState != null)
            {
                context.AddDetail("oldState", oldState);
            }

            if (requestedState != null)
            {
                context.AddDetail("requestedState", requestedState);
            }

            GCDiagnostics.Emit(
                code,
                GCDiagnosticSeverity.Warning,
                GCDiagnosticSourceAreas.State,
                message,
                context
            );
        }
