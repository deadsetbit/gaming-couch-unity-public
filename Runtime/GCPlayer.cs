                EmitEliminationTransitionDiagnostic("SetEliminatedPermanent", transition);
                return;
            }

            ApplyEliminationTransition(
                transition,
                GCPlayerStateTimestampTarget.Permanent,
                "permanently eliminated"
            );
        }

